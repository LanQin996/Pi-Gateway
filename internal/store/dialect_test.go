func TestSingleConnectionLegacyMigrationCompletes(t *testing.T) {
	const childPathEnv = "PI_GATEWAY_TEST_SINGLE_CONNECTION_LEGACY_PATH"
	if path := os.Getenv(childPathEnv); path != "" {
		s, err := OpenOptions(Options{Path: path, MaxOpenConns: 1, MaxIdleConns: 1, ConnMaxLifetime: time.Minute})
		if err != nil {
			t.Fatal(err)
		}
		defer s.Close()
		if limit := s.DB().Stats().MaxOpenConnections; limit != 1 {
			t.Fatalf("runtime connection limit=%d", limit)
		}
		if _, err := s.ListKeys(context.Background()); err != nil {
			t.Fatal(err)
		}
		backups, err := filepath.Glob(path + ".bak-*")
		if err != nil || len(backups) != 1 {
			t.Fatalf("legacy backups=%v err=%v", backups, err)
		}
		return
	}
	path := storeTestPath(t)
	db := makeLegacyPool(t, path)
	if err := db.Close(); err != nil {
		t.Fatal(err)
	}
	// Bound the regression in a child process so a pool deadlock cannot leave
	// an uninterruptible goroutine holding this test's SQLite fixture open.
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, os.Args[0], "-test.run=^TestSingleConnectionLegacyMigrationCompletes$", "-test.v")
	cmd.Env = append(os.Environ(), childPathEnv+"="+path)
	output, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		t.Fatalf("single-connection migration did not finish in time: %v\n%s", ctx.Err(), output)
	}
	if err != nil {
		t.Fatalf("legacy migration subprocess: %v\n%s", err, output)
	}
}

