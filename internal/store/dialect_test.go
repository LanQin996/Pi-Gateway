func TestPostgresPlaceholders(t *testing.T) {
	input := "SELECT ?, '?', 'it''s ?', \"?\", $$?$$, $body$?$body$, ??, ? -- ?\n/* ? /* ? */ ? */ WHERE id=?"
	want := "SELECT $1, '?', 'it''s ?', \"?\", $$?$$, $body$?$body$, ?, $2 -- ?\n/* ? /* ? */ ? */ WHERE id=$3"
	if got := postgresPlaceholders(input); got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
	if got := (&Store{driver: "sqlite"}).Rebind(input); got != input {
		t.Fatalf("SQLite SQL changed: %q", got)
	}
}

func TestPostgresProxyTriggerDollarQuotes(t *testing.T) {
	functions := 0
	for _, statement := range postgresProxyBindingSchema {
		if !strings.Contains(statement, "CREATE OR REPLACE FUNCTION") {
			continue
		}
		functions++
		if strings.Count(statement, "$proxy$") != 2 || !strings.Contains(statement, "AS $proxy$") || !strings.HasSuffix(strings.TrimSpace(statement), "END; $proxy$") {
			t.Fatalf("unclosed PL/pgSQL function quote: %q", statement)
		}
	}
	if functions != 2 {
		t.Fatalf("function count=%d", functions)
	}
}

func TestPostgresConnectionErrorDoesNotLeakDSN(t *testing.T) {
	// Invalid connect_timeout is rejected during parsing, before any network dial.
	for _, dsn := range []string{
		"postgres://user:secret-user@example.invalid/db?password=secret-query&connect_timeout=bad",
		"host=example.invalid password=secret-keyword connect_timeout=bad",
	} {
		s, err := OpenOptions(Options{Driver: "postgres", DSN: dsn})
		if err == nil {
			s.Close()
			t.Fatal("invalid DSN accepted")
		}
		if strings.Contains(err.Error(), "secret") || strings.Contains(err.Error(), "example.invalid") || strings.Contains(err.Error(), "password") {
			t.Fatalf("leaked DSN: %v", err)
		}
		if !strings.Contains(err.Error(), "invalid connection configuration") {
			t.Fatalf("classification=%v", err)
		}
		if errors.Unwrap(err) != nil {
			t.Fatal("sanitized error retains secret-bearing cause")
		}
	}
	for _, phase := range []string{"open", "begin migration"} {
		err := postgresConnectionError(phase, errors.New("password=secret-connect"))
		if strings.Contains(err.Error(), "secret") || !strings.Contains(err.Error(), "connection failed") || errors.Unwrap(err) != nil {
			t.Fatalf("unsanitized connection failure: %v", err)
		}
	}
}

func TestPostgresDialect(t *testing.T) {
	s := &Store{driver: "postgres"}
	q := s.Rebind("SELECT " + accountColumns + " FROM accounts WHERE id=?")
	for _, bad := range []string{"json_group_array", "json_object(", "json(g.", "id=?"} {
		if strings.Contains(q, bad) {
			t.Errorf("PostgreSQL account SQL contains %q: %s", bad, q)
		}
	}
	if !strings.Contains(q, "json_agg(group_id ORDER BY group_id)") || !strings.Contains(q, "id=$1") {
		t.Fatal(q)
	}
	for input, want := range map[string]string{
		"instr(lower(name),lower(?))":                 "strpos(lower(name),lower($1))",
		"MAX(cooldown_until,?)":                       "GREATEST(cooldown_until,$1)",
		"CAST(count(*)*0.95 AS INTEGER)":              "CAST(FLOOR(count(*)*0.95) AS BIGINT)",
		"CAST(AVG(NULLIF(duration_ms,0)) AS INTEGER)": "CAST(TRUNC(AVG(NULLIF(duration_ms,0))) AS BIGINT)",
	} {
		if got := s.Rebind(input); got != want {
			t.Errorf("%s => %s, want %s", input, got, want)
		}
	}
	schema := postgresSchema(schemaSQL)
	for _, bad := range []string{"AUTOINCREMENT", "INTEGER", "REAL"} {
		if strings.Contains(schema, bad) {
			t.Errorf("schema contains %s", bad)
		}
	}
	if strings.Count(schema, "GENERATED BY DEFAULT AS IDENTITY") != 7 {
		t.Fatal("missing identity columns")
	}
	if !errors.Is(groupWriteError(&pgconn.PgError{Code: "23505", ConstraintName: "account_groups_name_key"}), ErrGroupNameConflict) {
		t.Fatal("PostgreSQL unique error not translated")
	}
}

