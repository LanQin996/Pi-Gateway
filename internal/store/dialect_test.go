func TestPostgresSchemaVersionLedgerOffline(t *testing.T) {
	// The small version ledger uses portable SQL; exercise its real transaction
	// behavior on SQLite without requiring a PostgreSQL service locally.
	s := openTestStore(t)
	ctx := context.Background()
	tx, err := s.DB().BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	if version, err := checkPostgresSchemaVersion(ctx, tx); err != nil || version != 0 {
		t.Fatalf("fresh version=%d err=%v", version, err)
	}
	if err := recordPostgresSchemaVersion(ctx, tx); err != nil {
		t.Fatal(err)
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	tx, err = s.DB().BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	if version, err := checkPostgresSchemaVersion(ctx, tx); err != nil || version != postgresSchemaVersion {
		t.Fatalf("persisted version=%d err=%v", version, err)
	}
	var appliedAt int64
	if err := tx.QueryRowContext(ctx, `SELECT applied_at FROM schema_migrations WHERE version=$1`, postgresSchemaVersion).Scan(&appliedAt); err != nil || appliedAt <= 0 {
		t.Fatalf("applied_at=%d err=%v", appliedAt, err)
	}
	if _, err := tx.ExecContext(ctx, `INSERT INTO schema_migrations(version,applied_at) VALUES ($1,$2)`, postgresSchemaVersion+1, NowMS()); err != nil {
		t.Fatal(err)
	}
	if _, err := checkPostgresSchemaVersion(ctx, tx); err == nil || !strings.Contains(err.Error(), "newer than supported") {
		t.Fatalf("accepted future schema: %v", err)
	}
	if err := tx.Rollback(); err != nil {
		t.Fatal(err)
	}
	var version int64
	if err := s.DB().QueryRow(`SELECT MAX(version) FROM schema_migrations`).Scan(&version); err != nil || version != postgresSchemaVersion {
		t.Fatalf("rollback version=%d err=%v", version, err)
	}
}

