/** Presentation only: never mutate the stored name, even when it is localized. */
export function ruleDisplayName(rule: Pick<Rule, 'name' | 'source' | 'legacy_name'>, locale: string): string {
    if (rule.source === 'legacy' && rule.legacy_name === rule.name && Object.hasOwn(legacyRuleActions, rule.name)) return ruleLabel('action', legacyRuleActions[rule.name]!, locale)
    return rule.name
}

export function ruleLabel(group: string, value: string, locale: string): string {
    return ruleLabels[group]?.get(value)?.[locale === 'zh-CN' ? 1 : 0] ?? value
}

export function ruleFieldLabel(field: Pick<RuleField, 'name' | 'label'>, locale: string): string {
    if (ruleLabels.field?.has(field.name)) return ruleLabel('field', field.name, locale)
    return field.label?.split(' / ')[locale === 'zh-CN' ? 0 : 1] ?? field.name
}

export function ruleOptionLabel(value: string, locale: string): string {
    for (const group of ['option', 'phase', 'source', 'condition']) if (ruleLabels[group]?.get(value)) return ruleLabel(group, value, locale)
    return value
}

export function localizedConditionSummary(condition: RuleCondition, locale: string): string {
    const label = ruleLabel('condition', condition.op, locale)
    if (condition.conditions) return `${label} (${condition.conditions.map(c => localizedConditionSummary(c, locale)).join(' · ')})`
    return condition.path ? `${label} · ${condition.path}` : label
}
